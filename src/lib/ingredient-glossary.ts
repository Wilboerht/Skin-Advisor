/**
 * 查询成分科普信息
 *
 * @param name 成分名（支持全称或别名，如 "烟酰胺"、"玻尿酸"）
 * @returns 命中时返回 { title, description }，未命中返回 undefined
 *
 * @example
 * lookupIngredient("烟酰胺")
 * // => { title: "烟酰胺（维生素B3）", description: "全能型护肤成分..." }
 *
 * lookupIngredient("西洋参")
 * // => undefined
 */
export function lookupIngredient(name: string): IngredientInfo | undefined {
  if (!name || typeof name !== "string") return undefined;
  const trimmed = name.trim();
  if (!trimmed) return undefined;

  // 精确匹配
  const direct = GLOSSARY.get(trimmed);
  if (direct) return direct;

  // 模糊匹配：成分名可能包含额外后缀（如 "透明质酸钠（玻尿酸）"）
  for (const [key, value] of GLOSSARY) {
    if (trimmed.includes(key) || key.includes(trimmed)) {
      return value;
    }
  }

  return undefined;
}

/**
 * 批量查询多个成分
 */
export function lookupIngredients(names: string[]): (IngredientInfo | undefined)[] {
  return names.map((name) => lookupIngredient(name));
}
